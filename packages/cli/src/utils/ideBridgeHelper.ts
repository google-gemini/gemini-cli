/**
 * In-container half of the sandbox IDE bridge (see ./ideBridge.ts).
 *
 * The host-side launcher writes {@link IDE_BRIDGE_HELPER_SOURCE} into the
 * sandbox temp directory, which is already bind-mounted into the container,
 * and runs it in two roles:
 *
 * - `serve <socket>`: started by the host via `docker exec -i`. Listens on a
 *   Unix socket inside the container and relays bytes between the socket and
 *   its own stdio, i.e. the exec pipe back to the host.
 * - `connect <socket>`: spawned inside the container by the CLI's stdio MCP
 *   transport (`GEMINI_CLI_IDE_SERVER_STDIO_COMMAND`). Connects to that socket
 *   and relays bytes between the socket and its stdio.
 *
 * Only plain Node built-ins are used so the script runs on whatever `node`
 * the sandbox image provides, independently of the CLI version inside it.
 * Everything stays inside the sandbox's own namespaces, which is why this
 * works under gVisor as well as runc.
 */

export const IDE_BRIDGE_HELPER_FILENAME = 'ide-bridge.js';

/** Socket path inside the container (its private /tmp, never a host mount). */
export const IDE_BRIDGE_SOCKET_PATH = '/tmp/gemini-ide-bridge.sock';

/** Printed to stderr by `serve` once the socket is listening. */
export const IDE_BRIDGE_READY_MARKER = 'gemini-ide-bridge: listening';

/** How long `connect` keeps retrying while the host brings the bridge up. */
export const IDE_BRIDGE_CONNECT_TIMEOUT_MS = 30_000;

export const IDE_BRIDGE_HELPER_SOURCE = `// Gemini CLI sandbox IDE bridge helper. Generated by the sandbox launcher.
'use strict';
const net = require('node:net');
const fs = require('node:fs');

const [mode, socketPath] = process.argv.slice(2);
const READY_MARKER = ${JSON.stringify(IDE_BRIDGE_READY_MARKER)};
const CONNECT_TIMEOUT_MS = ${IDE_BRIDGE_CONNECT_TIMEOUT_MS};

function fail(message) {
  process.stderr.write('gemini-ide-bridge: ' + message + '\\n');
  process.exit(1);
}

// Host side of the container: exec'd by the launcher, stdio is the exec pipe.
function serve() {
  try {
    fs.unlinkSync(socketPath);
  } catch (_) {
    // no stale socket
  }
  let session = null;
  // Host -> sandbox traffic is newline-delimited JSON-RPC. Forward whole
  // messages only, and only to a connected session: a message that started
  // before the session attached is dropped in full rather than delivered as
  // a fragment that would break the CLI's framing.
  let pending = '';
  let skipPartialLine = false;
  process.stdin.setEncoding('utf8');
  process.stdin.on('data', (chunk) => {
    pending += chunk;
    let newline;
    while ((newline = pending.indexOf('\\n')) !== -1) {
      const line = pending.slice(0, newline + 1);
      pending = pending.slice(newline + 1);
      if (skipPartialLine) {
        skipPartialLine = false;
        continue;
      }
      if (session) session.write(line);
    }
  });
  // Sandbox -> host traffic is passed through as is; if a connector dies in
  // the middle of a message, terminate the fragment so it cannot be glued to
  // the next session's first message on the host side.
  let lastByteWasNewline = true;
  const server = net.createServer((socket) => {
    if (session) {
      // One CLI session at a time; a reconnecting CLI gets the socket once
      // the previous connector has gone away.
      socket.destroy();
      return;
    }
    session = socket;
    skipPartialLine = pending.length > 0;
    socket.on('error', () => {});
    socket.on('data', (chunk) => {
      lastByteWasNewline = chunk[chunk.length - 1] === 0x0a;
      process.stdout.write(chunk);
    });
    socket.on('close', () => {
      if (!lastByteWasNewline) {
        process.stdout.write('\\n');
        lastByteWasNewline = true;
      }
      session = null;
    });
  });
  server.on('error', (err) => fail(err.message));
  server.listen(socketPath, () => {
    try {
      fs.chmodSync(socketPath, 0o600);
    } catch (_) {
      // best effort
    }
    process.stderr.write(READY_MARKER + '\\n');
  });
  // The launcher closing the pipe means the sandbox is shutting down. stdin
  // stays in flowing mode so 'end' fires promptly even while no session is
  // attached (and so the host never blocks on pipe backpressure).
  process.stdin.on('end', () => process.exit(0));
  process.stdin.on('error', () => process.exit(0));
}

// CLI side: spawned by the stdio MCP transport inside the container.
function connect() {
  const deadline = Date.now() + CONNECT_TIMEOUT_MS;
  const attempt = () => {
    const socket = net.connect(socketPath);
    let connected = false;
    socket.on('connect', () => {
      connected = true;
      process.stdin.pipe(socket);
      socket.pipe(process.stdout);
    });
    socket.on('close', () => {
      if (connected) process.exit(0);
    });
    socket.on('error', (err) => {
      if (connected) process.exit(1);
      const retryable = err.code === 'ENOENT' || err.code === 'ECONNREFUSED';
      if (retryable && Date.now() < deadline) {
        setTimeout(attempt, 250);
        return;
      }
      fail('cannot reach the host bridge: ' + err.message);
    });
  };
  attempt();
}

if (!socketPath) fail('usage: ide-bridge.js <serve|connect> <socket>');
if (mode === 'serve') serve();
else if (mode === 'connect') connect();
else fail('unknown mode ' + mode);
`;
